export const getLaterExamSession = (
  month1?: string,
  year1?: string | number,
  month2?: string,
  year2?: string | number
): { month: string; year: string } => {
  const y1 = parseInt(String(year1 || '0'), 10) || 0;
  const y2 = parseInt(String(year2 || '0'), 10) || 0;
  const m1 = MONTH_ORDER[(month1 || '').toLowerCase().trim()] || 0;
  const m2 = MONTH_ORDER[(month2 || '').toLowerCase().trim()] || 0;

  if (!y1 && y2) return { month: month2 || '', year: String(year2 || '') };
  if (!y2 && y1) return { month: month1 || '', year: String(year1 || '') };

  if (y1 > y2) return { month: month1 || '', year: String(year1 || '') };
  if (y2 > y1) return { month: month2 || '', year: String(year2 || '') };

  if (m2 > m1) return { month: month2 || '', year: String(year2 || year1 || '') };
  if (m1 > m2) return { month: month1 || '', year: String(year1 || year2 || '') };

  return {
    month: month2 || month1 || '',
    year: String(year2 || year1 || '')
  };
};
